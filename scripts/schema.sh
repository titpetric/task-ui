#!/usr/bin/env bash
# Regenerate the data model from the migrations.
#
#   scripts/schema.sh
#
# Applies schema/*.up.sql to a throwaway SQLite file, lints the schema,
# then writes schema/docs, schema/schema.yml, the Go types under model/ and
# the front end's test schema.
# Needs mig: go install github.com/go-bridget/mig@latest
set -euo pipefail
cd "$(dirname "$0")/.."

db="$(mktemp -u).db"
trap 'rm -f "$db"' EXIT
export MIG_DB_DSN="sqlite://file:${db}"

mig migrate --project task-ui --path ./schema --apply
mig lint
mig docs --output=./schema/docs
mig docs --output=./schema --yaml --output-file schema.yml
mig gen --go.fill-json --output=./model

# The front end's fixtures open a database and cannot reach this directory:
# a test tree resolves every path inside its own root. They get the schema
# the migrations end at, which is what a fixture needs - it has no history to
# replay - as one file their setup hook hands to the driver.
front="phpfront/app/tests/schema.sql"
printf -- '-- Code generated by scripts/schema.sh from schema/*.up.sql. DO NOT EDIT.\n\n' > "${front}"
sqlite3 "${db}" '.schema --nosys' >> "${front}"
